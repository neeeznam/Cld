export function fitName(lang: Lang, fid: string): string {
  if (lang === 'en' && FIT_EN[fid]) return FIT_EN[fid];
  return FIT[fid]?.n ?? fid;
}

export function paramLabel(lang: Lang, fid: string, k: string): string {
  const f = FIT[fid];
  const z = f?.p.find((x) => x.k === k);
  if (lang === 'en') return PARAM_EN[k] ?? z?.l ?? k;
  return z?.l ?? k;
}

