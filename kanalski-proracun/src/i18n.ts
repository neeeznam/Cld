export type T = (k: Key, args?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const D = lang === 'en' ? EN : SR;
  return (k, args) => fill(D[k] ?? String(k), args);
}

function fill(s: string, args?: Record<string, string | number>): string {
  if (!args) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (args[k] != null ? String(args[k]) : ''));
}

export function warnText(lang: Lang, w: Warn): string {
  const D = lang === 'en' ? WARN_EN : WARN_SR;
  return fill(D[w.code] ?? w.code, w.args);
}

